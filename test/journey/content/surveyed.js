import fs from 'node:fs'

const load = (name) => JSON.parse(fs.readFileSync(new URL(`../data/${name}.json`, import.meta.url), 'utf8')) // source: generated by scripts/generate-surface.mjs from the survey

/** Pages that loaded in the survey, keyed by `<app>-<slug>`. */
export const surveyed = Object.fromEntries(load('pages').map((p) => [p.key, p])) // source: data/pages.json (survey of both apps, 2026-11-02)

/** Create forms with the client validators observed after an empty save. */
export const forms = Object.fromEntries(load('forms').map((f) => [f.form, f])) // source: data/forms.json (survey 2026-11-02)
