// Generates features/internal/internal-roles.feature and internal-limited.feature from the role matrix in content/internal.js.
import fs from 'node:fs'
import { internal } from '../content/internal.js'

const w = Math.max(...internal.matrix.map((m) => m.path.length))
const rows = internal.matrix.map((m) => `      | ${m.path.padEnd(w)} |`).join('\n')

const outline = (id, title) => `  @${id} @regression
  Scenario Outline: ${title}
    ${id === 'TC-INT-110' ? '' : 'Given a signed-in limited user\n    '}When the user requests the internal address "<path>"
    Then access to that page matches the roles the account holds

    Examples:
      | ${'path'.padEnd(w)} |
${rows}
`

const roles = `@feature:internal-roles @role:internal
Feature: Internal role-based access
  Each page opens only for an account that holds its role (INTERNAL_WEB_ROLES lists the roles the test account holds) and is refused with 403 Access Denied otherwise.
  Generated by scripts/gen-roles-feature.js; source: Authorization/PtlPolicies.cs and the [Authorize] attributes on each controller.

${outline('TC-INT-110', 'Page access matches the roles of the main account')}
  @TC-INT-111 @regression
  Scenario: Assessor page opens for an account with the Assessor role
    Given the account holds the "Assessor" role
    When the user requests the internal address "/Assessor"
    Then the page heading starts with "Assessor"

  @TC-INT-112 @regression
  Scenario: Results Sign-off page opens for an account with the Results Sign-off role
    Given the account holds the "ResultsSignOff" role
    When the user requests the internal address "/Results%20Sign-off"
    Then the page heading starts with "Results Sign-off"

  @TC-INT-113 @regression
  Scenario: Invoice Generation opens for an account with Contracts Admin and Generate Invoices
    Given the account holds the "InvoiceGeneration" role
    When the user requests the internal address "/Invoice/Index"
    Then the page heading starts with "Invoice Generation"

  @TC-INT-114 @regression
  Scenario Outline: Distribution pages that need the Internal User role open for an account that holds it
    Given the account holds the "InternalUser" role
    When the user requests the internal address "<path>"
    Then the page heading starts with "<heading>"

    Examples:
      | path                                         | heading             |
      | /Distribution/Preparation?year=2026&monthId=4 | Sample preparation  |
      | /Distribution/Packaging?year=2026&monthId=4   | Sample packaging    |
      | /Distribution/ResultsReceipt?year=2026&monthId=4 | Results Receipt  |
`
const limited = `@feature:internal-limited @role:limited
Feature: Internal access for a low-privilege account
  Needs INTERNAL_WEB_LIMITED_USER / _PASSWORD (and INTERNAL_WEB_LIMITED_ROLES, empty by default). Skips itself when the account is not configured.
  Generated by scripts/gen-roles-feature.js.

${outline('TC-INT-120', 'Page access matches the roles of the limited account')}`

fs.writeFileSync('features/internal/internal-roles.feature', roles)
fs.writeFileSync('features/internal/internal-limited.feature', limited)
console.log(`${internal.matrix.length} matrix rows`)
